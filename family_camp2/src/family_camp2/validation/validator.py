"""The single validation entry point required by FR-40/FR-41.

Works on any Timetable - one generated by a solver, or hand-built in a
test - with no solver-specific code anywhere in this module.
"""

from __future__ import annotations

from datetime import timedelta

from family_camp2.domain import Activity, Camper, Session, Timetable
from family_camp2.validation.class1 import check_class1
from family_camp2.validation.class2 import Tier0Weights, check_class2, score_tier0
from family_camp2.validation.idle import find_idle_slots
from family_camp2.validation.report import ValidationReport
from family_camp2.validation.tiers import score_tier1, score_tier2

__all__ = ["validate"]


def validate(
    timetable: Timetable,
    campers: list[Camper],
    sessions: list[Session],
    tier0_weights: Tier0Weights = Tier0Weights(),
    compulsory: frozenset[Activity] = frozenset(),
    idle_granularity: timedelta = timedelta(hours=1),
) -> ValidationReport:
    class1 = check_class1(timetable)
    class2 = check_class2(timetable, campers, compulsory)

    return ValidationReport(
        class1=class1,
        class2=class2,
        tier0_score=score_tier0(class2, tier0_weights),
        tier1_score=score_tier1(timetable, campers),
        tier2_score=score_tier2(timetable, sessions),
        idle=find_idle_slots(timetable, campers, sessions, idle_granularity),
    )
